import "server-only";
import * as argon2 from "@node-rs/argon2";
import bcrypt from "bcryptjs";
import crypto from "crypto";

/**
 * Enterprise Hashing & Cryptographic Service
 * 
 * - Passwords & Client Secrets: Argon2id (OWASP 2026 Recommended: 19 MiB memory, 2 iterations, 1 parallelism)
 * - Ephemeral Codes & Tokens (OTP, 2FA, Backup codes): WebCrypto Salted SHA-256 with Constant-Time Equality
 * - Zero Downtime Migration: Transparent backward-compatibility verification for legacy bcrypt ($2a$, $2b$, $2y$) hashes
 */

// OWASP Recommended Argon2id parameters
const ARGON2_OPTIONS: argon2.Options = {
  memoryCost: 19456, // 19 MiB
  timeCost: 2,       // 2 iterations
  outputLen: 32,
  parallelism: 1,
  algorithm: 2,      // Algorithm.Argon2id
};

/**
 * Checks if a hash was generated by legacy bcrypt and should be upgraded to Argon2id.
 */
export function needsRehash(hash?: string | null): boolean {
  if (!hash) return false;
  return hash.startsWith("$2a$") || hash.startsWith("$2b$") || hash.startsWith("$2y$");
}

/**
 * Hashes a user password using Argon2id.
 * Non-blocking, multithreaded via native Rust N-API.
 */
export async function hashPassword(password: string): Promise<string> {
  return await argon2.hash(password, ARGON2_OPTIONS);
}

/**
 * Verifies a password against an Argon2id or legacy bcrypt hash.
 */
export async function verifyPassword(password: string, hash?: string | null): Promise<boolean> {
  if (!password || !hash) return false;

  // 1. Argon2id ($argon2id$, $argon2i$, $argon2d$)
  if (hash.startsWith("$argon2")) {
    try {
      return await argon2.verify(hash, password);
    } catch {
      return false;
    }
  }

  // 2. Backward compatibility: Legacy Bcrypt
  if (hash.startsWith("$2a$") || hash.startsWith("$2b$") || hash.startsWith("$2y$")) {
    try {
      return await bcrypt.compare(password, hash);
    } catch {
      return false;
    }
  }

  return false;
}

/**
 * Hashes an OAuth 2.0 client secret using Argon2id.
 */
export async function hashClientSecret(secret: string): Promise<string> {
  return await argon2.hash(secret, ARGON2_OPTIONS);
}

