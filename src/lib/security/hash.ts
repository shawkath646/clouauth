/**
 * Hashes an ephemeral verification code (OTP, email confirmation, 2FA code, backup recovery code)
 * using WebCrypto SHA-256 with a unique 128-bit cryptographic salt.
 * 
 * Sub-millisecond execution, completely non-blocking, zero event-loop lag.
 */
export async function hashCode(code: string): Promise<string> {
  const cleanCode = code.trim();
  const salt = crypto.getRandomValues(new Uint8Array(16));
  const saltHex = Buffer.from(salt).toString("hex");

  const encoder = new TextEncoder();
  const data = encoder.encode(`${saltHex}:${cleanCode}`);
  const hashBuffer = await crypto.subtle.digest("SHA-256", data);
  const hashHex = Buffer.from(hashBuffer).toString("hex");

  return `wc_sha256$${saltHex}$${hashHex}`;
}

/**
 * Verifies an ephemeral code against a WebCrypto, Argon2id, or legacy Bcrypt hash
 * using constant-time timing-safe comparison.
 */
export async function verifyCode(code: string, storedHash?: string | null): Promise<boolean> {
  if (!code || !storedHash) return false;
  const cleanCode = code.trim();

  // 1. Modern WebCrypto salted SHA-256
  if (storedHash.startsWith("wc_sha256$")) {
    const parts = storedHash.split("$");
    if (parts.length !== 3) return false;
    const [, saltHex, expectedHex] = parts;

    const encoder = new TextEncoder();
    const data = encoder.encode(`${saltHex}:${cleanCode}`);
    const hashBuffer = await crypto.subtle.digest("SHA-256", data);
    const hashHex = Buffer.from(hashBuffer).toString("hex");

    if (hashHex.length !== expectedHex.length) return false;
    return crypto.timingSafeEqual(
      Buffer.from(hashHex, "hex"),
      Buffer.from(expectedHex, "hex")
    );
  }

  // 2. Legacy Bcrypt ($2a$, $2b$, $2y$)
  if (
    storedHash.startsWith("$2a$") ||
    storedHash.startsWith("$2b$") ||
    storedHash.startsWith("$2y$")
  ) {
    try {
      return await bcrypt.compare(cleanCode, storedHash);
    } catch {
      return false;
    }
  }

  // 3. Argon2id fallback
  if (storedHash.startsWith("$argon2")) {
    try {
      return await argon2.verify(storedHash, cleanCode);
    } catch {
      return false;
    }
  }

  return false;
}
